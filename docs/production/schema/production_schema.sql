-- Source of truth reconstructed from the pilot database structure (DDL only,
-- NO user data). Captures the tables that live outside Drizzle migrations
-- (contacts, push_subscriptions, user_settings) plus the Drizzle-managed
-- feedback table, so a fresh production database is reproducible.
--
-- Run against the NEW Neon production branch/database only. Safe to re-run.
-- Do NOT run against the pilot database.
